import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import nextEnv from '@next/env';
import pg from 'pg';

nextEnv.loadEnvConfig(process.cwd(), true);
const root = new URL('../', import.meta.url);
const command = process.argv[2] || 'setup';
const metadata = `
  create schema if not exists farmtech_meta;
  revoke all on schema farmtech_meta from public, anon, authenticated;
  create table if not exists farmtech_meta.migrations (
    name text primary key, checksum text not null, applied_at timestamptz not null default now()
  );
`;

async function migrations() {
  const directory = new URL('supabase/migrations/', root);
  const names = (await readdir(directory)).filter(name => /^\d+.*\.sql$/.test(name)).sort();
  return Promise.all(names.map(async name => {
    const sql = await readFile(new URL(name, directory), 'utf8');
    return { name, sql, checksum: createHash('sha256').update(sql).digest('hex') };
  }));
}

// SQL Editor and direct PostgreSQL setup share the same migration history.
async function exportSQL(files, seed) {
  const blocks = files.map(({ name, sql, checksum }) => {
    const tag = '$migration_' + name.replace(/\W/g, '_') + '$';
    return `do ${tag}
begin
  if exists (select 1 from farmtech_meta.migrations where name = '${name}' and checksum <> '${checksum}') then
    raise exception 'Migration changed: ${name}';
  end if;
  if not exists (select 1 from farmtech_meta.migrations where name = '${name}') then
${sql}
    insert into farmtech_meta.migrations (name, checksum) values ('${name}', '${checksum}');
  end if;
end ${tag};`;
  });
  const output = new URL('supabase/setup-demo.sql', root);
  await mkdir(new URL('supabase/', root), { recursive: true });
  await writeFile(output, `-- Generated by npm run db:sql. Run the ENTIRE file in Supabase SQL Editor.\n-- Re-running preserves app data; only reserved demo accounts are reset.\nbegin;\nselect pg_advisory_xact_lock(4284199);\n${metadata}\n${blocks.join('\n\n')}\n${seed}\nnotify pgrst, 'reload schema';\ncommit;\n`);
  console.log(`SQL siap: ${fileURLToPath(output)}`);
}

async function run() {
  if (!['setup', 'migrate', 'seed', 'sql'].includes(command)) throw new Error('Gunakan setup, migrate, seed, atau sql.');
  const files = await migrations();
  const seed = await readFile(new URL('supabase/seed.sql', root), 'utf8');
  if (command === 'sql') return exportSQL(files, seed);

  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) throw new Error('DATABASE_URL belum diisi. Alternatif: npm run db:sql, lalu jalankan supabase/setup-demo.sql di SQL Editor Supabase.');
  const client = new pg.Client({ connectionString, connectionTimeoutMillis: 15000 });
  try {
    await client.connect();
    await client.query('begin');
    await client.query('select pg_advisory_xact_lock(4284199)');
    await client.query(metadata);
    if (command !== 'seed') {
      for (const file of files) {
        const { rows } = await client.query('select checksum from farmtech_meta.migrations where name = $1', [file.name]);
        if (rows.length) {
          if (rows[0].checksum !== file.checksum) throw new Error(`Migration berubah setelah diterapkan: ${file.name}`);
          console.log(`Sudah diterapkan: ${file.name}`);
          continue;
        }
        await client.query(file.sql);
        await client.query('insert into farmtech_meta.migrations(name, checksum) values ($1, $2)', [file.name, file.checksum]);
        console.log(`Migration: ${file.name}`);
      }
    }
    if (command !== 'migrate') {
      await client.query(seed);
      console.log('Tiga akun demo aktif dan data awal siap.');
    }
    await client.query("notify pgrst, 'reload schema'");
    await client.query('commit');
    console.log('Database siap. Jalankan npm run db:verify untuk memeriksa semua role.');
  } catch (error) {
    await client.query('rollback').catch(() => {});
    throw error;
  } finally {
    await client.end();
  }
}

run().catch(error => {
  // Do not print connection strings or credentials in terminal output.
  let message = error.message || 'Setup database gagal.';
  for (const key of ['DATABASE_URL', 'NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY']) {
    if (process.env[key]) message = message.replaceAll(process.env[key], '[REDACTED]');
  }
  console.error(message);
  process.exitCode = 1;
});
